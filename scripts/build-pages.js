'use strict';
// Generates backend/lib/pages.js from public/*.html (+ public/vendor/blob-client.js if present).
// Why: on Vercel the CDN normally serves public/**. If it ever does not (misconfigured project,
// stale routing), Express can still serve the same pages from this module (no filesystem access
// at runtime, nothing is written). The CDN always wins when it serves the file.
// Run: npm run build:pages   (also runs inside `npm run build` and `npm run build:client`)
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const SOURCES = ['index.html', 'admin.html', '404.html', 'vendor/blob-client.js'];

function collect() {
  const files = {};
  for (const name of SOURCES) {
    const p = path.join(root, 'public', name);
    if (fs.existsSync(p)) files[name] = fs.readFileSync(p, 'utf8');
  }
  return files;
}
function hashOf(files) {
  const h = crypto.createHash('sha256');
  for (const name of Object.keys(files).sort()) h.update(name + '\0' + files[name] + '\0');
  return h.digest('hex');
}

if (require.main === module) {
  const files = collect();
  for (const required of ['index.html', 'admin.html']) {
    if (!files[required]) { console.error(`build-pages: public/${required} is missing`); process.exit(1); }
  }
  const out = path.join(root, 'backend', 'lib', 'pages.js');
  const body = `'use strict';\n// GENERATED by scripts/build-pages.js from public/*. Do not edit by hand.\nmodule.exports = {\n  hash: ${JSON.stringify(hashOf(files))},\n  files: ${JSON.stringify(files)}\n};\n`;
  fs.writeFileSync(out, body);
  console.log(`build-pages: wrote backend/lib/pages.js (${Object.keys(files).join(', ')})`);
}

module.exports = { collect, hashOf };
